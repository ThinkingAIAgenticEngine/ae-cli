import {
  compactInput,
  createPersonalSemanticPreferenceCommand,
  optionalKeywords,
  optionalJsonStringArray,
  optionalSources,
  optionalResourceRefs,
  optionalString,
  validatePersonalSemanticWrite,
} from './shared.js';

export const personalSemanticPreferenceUpdate = createPersonalSemanticPreferenceCommand({
  resource: '',
  command: 'update',
  capabilityId: 'business_semantics.personal_context.update',
  description: 'Update one personal semantic preference using optimistic locking.',
  flags: [
    { name: 'project-id', type: 'number', required: true, desc: 'Positive project ID, or -1 for current-user global personal semantics.', alias: 'p' },
    { name: 'id', type: 'string', required: true, desc: 'Preference ID returned by list/add.' },
    { name: 'expected-revision', type: 'number', required: true, desc: 'Revision returned by the latest read.', min: 1 },
    { name: 'context-type', type: 'string', required: true, desc: 'preference | business_rule | asset_context | experience | background.' },
    { name: 'title', type: 'string', required: true, desc: 'Distinct business concept, adding only a necessary scope or condition.', maxLength: 255 },
    { name: 'summary', type: 'string', required: true, desc: 'Compact selection summary with subject, applicability and key exclusions.', maxLength: 1000 },
    { name: 'content', type: 'string', required: true, desc: 'Full replacement content.', maxLength: 20000 },
    { name: 'keywords', type: 'json', desc: 'Optional JSON array of distinctive business phrases or confirmed aliases; avoid generic fragments.' },
    { name: 'resource-refs', type: 'json', desc: 'Ordered JSON asset references; required only for asset_context.' },
    { name: 'applicable-question', type: 'string', desc: 'Questions and boundaries where this rule applies.', maxLength: 1000 },
    { name: 'dependency-ids', type: 'json', desc: 'Explicit dependency IDs, in the same scope/project.' },
    { name: 'sources', type: 'json', desc: 'Source filenames as [{"name":"business-overview.docx"}]; optional input_file_id, or existing evidence_id. Keep paths and raw JSON local.' },
    { name: 'fresh-until-at', type: 'string', desc: 'Optional freshness expiration timestamp: yyyy-MM-dd HH:mm:ss.' },
    { name: 'request-id', type: 'string', desc: 'Optional idempotency key; generated when omitted.', maxLength: 128 },
  ],
  risk: 'write',
  validate: validatePersonalSemanticWrite,
  buildInput: (ctx) => compactInput({
    project_id: ctx.num('project-id'),
    id: ctx.str('id'),
    expected_revision: ctx.num('expected-revision'),
    context_type: ctx.str('context-type'),
    title: ctx.str('title'),
    summary: ctx.str('summary'),
    content: ctx.str('content'),
    keywords: optionalKeywords(ctx),
    applicable_question: optionalString(ctx, 'applicable-question'),
    dependency_ids: optionalJsonStringArray(ctx, 'dependency-ids', '--dependency-ids'),
    sources: optionalSources(ctx),
    resource_refs: optionalResourceRefs(ctx),
    fresh_until_at: optionalString(ctx, 'fresh-until-at'),
    request_id: optionalString(ctx, 'request-id'),
  }),
});
